#!/usr/bin/env python3
"""Build Port Readable coverage atlas from unmodified Forum (SIL OFL-1.1). Requires Pillow."""
from pathlib import Path
from PIL import Image,ImageFont,ImageDraw
import struct,hashlib,json
root=Path(__file__).resolve().parents[1];source=root/'assets/readable/Forum-Regular.ttf'
font=ImageFont.truetype(str(source),22);height=20;top=4;n=256
dc=bytearray(struct.pack('<6I',6,1,0,0,1,n)+bytes(n*4));tbl=bytearray(12+n*14);tbl[:5]=b'Woo!\1'
for i in range(n):
 ch=bytes([i]).decode('latin1') if i>=32 and i!=127 else ' '
 advance=max(1,round(font.getlength(ch)));bbox=font.getbbox(ch);left=min(0,bbox[0]);width=max(1,advance,bbox[2]-left)
 im=Image.new('L',(width,height));ImageDraw.Draw(im).text((-left,-top),ch,font=font,fill=255)
 rows=[im.tobytes()[y*width:(y+1)*width]for y in range(height)];rle=bytearray()
 for row in rows[::-1]:
  x=0
  while x<width:
   zero=row[x]==0;end=x+1
   while end<width and (row[end]==0)==zero and end-x<127:end+=1
   rle.append(128+end-x if zero else end-x)
   if not zero:rle.extend(row[x:end])
   x=end
  rle.append(128)
 struct.pack_into('<I',dc,24+i*4,len(dc));dc.extend(struct.pack('<8I',0,width,height,0,0,0,0,len(rle)));dc.extend(rle)
 at=12+i*14;struct.pack_into('<H',tbl,at,i);tbl[at+3]=advance;tbl[at+4]=height;struct.pack_into('<H',tbl,at+8,i)
out=root/'src/readable_font_data.hpp'
with out.open('w') as f:
 f.write('// Generated by scripts/build_readable_font.py. Font data: SIL OFL-1.1.\n// Copyright (c) 2011 Denis Masharov. See assets/readable/OFL.txt.\n// Converted font primary name: Port Readable.\n#pragma once\n#include <cstdint>\nnamespace d2mini::readable_data {\n')
 for name,data in [('tbl',tbl),('dc6',dc)]:
  f.write(f'inline constexpr std::uint8_t {name}[]={{\n')
  for at in range(0,len(data),32):f.write(','.join(str(b)for b in data[at:at+32])+',\n')
  f.write('};\n')
 f.write('}\n')
(root/'assets/readable/provenance.json').write_text(json.dumps({'source':'Forum-Regular.ttf','sha256':hashlib.sha256(source.read_bytes()).hexdigest(),'size':22,'canvas_height':height,'top_crop':top,'primary_converted_name':'Port Readable','license':'OFL.txt','rasterizer':'Pillow '+__import__('PIL').__version__},indent=2)+'\n')
